import { isPhysical, isProtectedSource, keyByCode, type KeyDef } from "./keys.ts";

/** Persisted remap: source physical key (KeyboardEvent.code) -> target key code. */
export interface RemapConfig {
  version: 1;
  /** Substring matched (case-insensitive) against Hyprland keyboard device names. */
  deviceMatch: string;
  mappings: Record<string, string>;
  /**
   * Swap Alt and Super for the matched keyboards (xkb option altwin:swap_alt_win). For boards that sit in
   * Mac mode, where the firmware already swaps them. Independent of the key mappings: it also applies on Revert.
   */
  swapAltSuper: boolean;
}

export const XKB_LAYOUT = "kbconfig";
export const XKB_VARIANT = "rover";

export class RemapError extends Error {}

export const emptyConfig = (): RemapConfig => ({ version: 1, deviceMatch: "rover-84", mappings: {}, swapAltSuper: false });

/** Validates untrusted input (HTTP body or file) and returns a clean config; drops identity mappings. */
export function parseConfig(input: unknown): RemapConfig {
  if (typeof input !== "object" || input === null) throw new RemapError("config must be an object");
  const raw = input as Record<string, unknown>;
  if (raw.version !== 1) throw new RemapError("unsupported config version");
  if (typeof raw.deviceMatch !== "string" || !/^[A-Za-z0-9._-]{2,64}$/.test(raw.deviceMatch)) {
    throw new RemapError("deviceMatch must be 2-64 chars of letters, digits, dot, underscore or dash");
  }
  if (typeof raw.mappings !== "object" || raw.mappings === null || Array.isArray(raw.mappings)) {
    throw new RemapError("mappings must be an object");
  }
  if (raw.swapAltSuper !== undefined && typeof raw.swapAltSuper !== "boolean") throw new RemapError("swapAltSuper must be true or false");
  const mappings: Record<string, string> = {};
  for (const [src, dst] of Object.entries(raw.mappings)) {
    const from = keyByCode(src);
    if (!from || !isPhysical(src)) throw new RemapError(`unknown source key: ${src}`);
    if (isProtectedSource(from)) throw new RemapError(`${from.label} is a modifier and cannot be remapped away yet`);
    if (typeof dst !== "string" || !keyByCode(dst)) throw new RemapError(`unknown target for ${src}: ${String(dst)}`);
    if (src !== dst) mappings[src] = dst;
  }
  return { version: 1, deviceMatch: raw.deviceMatch, mappings, swapAltSuper: raw.swapAltSuper === true };
}

function keyType(levels: string[], mod?: string): string {
  if (mod || levels.length === 1) return "ONE_LEVEL";
  const isLetterPair = /^[a-z]$/.test(levels[0]!) && levels[1] === levels[0]!.toUpperCase();
  return isLetterPair ? "ALPHABETIC" : "TWO_LEVEL";
}

/** Builds ~/.config/xkb/symbols/kbconfig: stock "us" plus one `replace key` per mapping. */
export function generateXkbSymbols(config: RemapConfig): string {
  const lines: string[] = [
    "// Generated by keyboard-config. Overwritten on every Apply; edit the app, not this file.",
    "default partial alphanumeric_keys modifier_keys",
    `xkb_symbols "${XKB_VARIANT}" {`,
    '    include "us"',
  ];
  const modMaps: string[] = [];
  for (const [src, dst] of Object.entries(config.mappings).sort(([a], [b]) => a.localeCompare(b))) {
    const from = keyByCode(src) as KeyDef;
    const to = keyByCode(dst) as KeyDef;
    const levels = to.levels.join(", ");
    lines.push(`    replace key <${from.xkb}> { type[Group1] = "${keyType(to.levels, to.mod)}", symbols[Group1] = [ ${levels} ] }; // ${from.label} -> ${to.label}`);
    if (to.mod) modMaps.push(`    modifier_map ${to.mod} { <${from.xkb}> };`);
  }
  lines.push(...modMaps, "};", "");
  return lines.join("\n");
}

const DEVICE_NAME = /^[A-Za-z0-9._-]+$/;
export const SWAP_ALT_SUPER = "altwin:swap_alt_win";

/**
 * `hl.device` statements for Hyprland, one per matched device. Names are validated before
 * interpolation. These are what `hyprctl eval` receives, so no line may start with "-":
 * hyprctl would parse a leading "--" comment as a flag.
 */
export function hyprlandDeviceCalls(deviceNames: string[], active: boolean, swapAltSuper = false): string[] {
  const options = swapAltSuper ? `, kb_options = "${SWAP_ALT_SUPER}"` : "";
  return deviceNames.map((name) => {
    if (!DEVICE_NAME.test(name)) throw new RemapError(`refusing unsafe device name: ${name}`);
    return active
      ? `hl.device({ name = "${name}", kb_layout = "${XKB_LAYOUT}", kb_variant = "${XKB_VARIANT}"${options} })`
      : `hl.device({ name = "${name}", kb_layout = "us", kb_variant = ""${options} })`;
  });
}

/** Same statements as a file Master can `dofile` from hyprland.lua so the remap survives reloads. */
export function generateHyprlandLua(deviceNames: string[], active: boolean, swapAltSuper = false): string {
  return ["-- Generated by keyboard-config. Safe to `dofile` from hyprland.lua; regenerated on Apply.", ...hyprlandDeviceCalls(deviceNames, active, swapAltSuper), ""].join("\n");
}

export const matchDevices = (all: string[], deviceMatch: string): string[] =>
  all.filter((n) => n.toLowerCase().includes(deviceMatch.toLowerCase()));
